def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Genera el informe de funciones irreconstruibles")
    ap.add_argument("--evidencia", type=Path, required=True)
    ap.add_argument("--json", type=Path, default=None)
    ap.add_argument("--salida", type=Path, required=True)
    args = ap.parse_args(argv)

    with open(args.evidencia, encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    res = json.loads(args.json.read_text(encoding="utf-8")) if args.json else {}

    tamaños = sorted(int(r["bytes_reales"]) for r in rows if r["bytes_reales"].isdigit())
    errs = Counter((r["dec_err_motor437"] or "(sin fila)").strip() for r in rows)
    ver = Counter(r["veredicto"] for r in rows)

    errores = "\n".join(
        "| `%s` | %d |" % (e.replace("|", "\\|"), n) for e, n in errs.most_common()
    )
    tabla = "\n".join(
        "| %d | `%s` | `%s` | %s | %s | `%s` | %s | **%s** |"
        % (
            i + 1,
            r["addr"],
            r["nombre"].replace("|", "\\|"),
            r["categoria"].split(" (")[0],
            r["bytes_reales"],
            (r["dec_err_motor437"] or "").replace("|", "\\|").strip(),
            r["primera_instr"],
            r["veredicto"],
        )
        for i, r in enumerate(rows)
    )
    thunks = [r for r in rows if r["veredicto"] == "THUNK"]
    if thunks:
        t0 = thunks[0]
        thunk_detalle = (
            "- `%s` (`%s`) — %s · %s · %s B · error: `%s`"
            % (
                t0["nombre"],
                t0["addr"],
                t0["orig"],
                t0["loc"],
                t0["bytes_reales"],
                (t0["dec_err_motor437"] or "").strip(),
            )
        )
        thunk_destino = (t0["rama_destino"] or "?").split(" ")[0]
    else:
        thunk_detalle = "_Ninguna: no hay thunks en la lista._"
        thunk_destino = "n/d"

    recon = [r for r in rows if r["veredicto"] == "RECONSTRUIBLE-CON-PISTA"]
    recon_detalle = "\n".join(
        "- `%s` (`%s`) — %s · %s"
        % (r["nombre"], r["addr"], r["orig"], r["loc"])
        for r in recon
    )

    def _pct(a, b):
        return ("%.1f" % (100.0 * a / max(1, b))).replace(".", ",")

    pf = _pct(res.get("prologo_fallo_sin", 0), res.get("prologo_fallo_n", 1))
    pc = _pct(res.get("prologo_ctrl_sin", 0), res.get("prologue_ctrl_n", 1))
    df = _pct(res.get("destino_rama_fallo", 0), res.get("destino_rama_fallo_n", 1))
    dc = _pct(res.get("destino_rama_ctrl", 0), res.get("destino_rama_ctrl_n", 1))

    txt = PLANTILLA.format(
        tmin=tamaños[0] if tamaños else "n/d",
        tmed=statistics.median(tamaños) if tamaños else "n/d",
        tmax=tamaños[-1] if tamaños else "n/d",
        n16=sum(1 for t in tamaños if t <= 16),
        n_thunk=ver.get("THUNK", 0),
        n_wrap=sum(1 for r in rows if r["wrapper"]),
        n_defer=sum(1 for r in rows if r["wrapper"] == "deferwrap"),
        n_clos=sum(1 for r in rows if r["wrapper"] == "closure"),
        n_go=sum(1 for r in rows if r["wrapper"] == "gowrap"),
        n_irrec=ver.get("IRRECONSTRUIBLE", 0),
        n_recon=ver.get("RECONSTRUIBLE-CON-PISTA", 0),
        errores=errores,
        ratio_fallo=("%.2f" % res["ratio_fallo"]).replace(".", ","),
        ratio_ctrl=("%.2f" % res["ratio_ctrl"]).replace(".", ","),
        ctrl_exactos=res["ctrl_exactos"],
        ctrl_n=res["ctrl_n"],
        mayores=res["fallo_mayores"],
        huecos=format(res["huecos_pclntab"], ",").replace(",", "."),
        pf=pf,
        pc=pc,
        df=df,
        dc=dc,
        recon_detalle=recon_detalle,
        thunk_detalle=thunk_detalle,
        thunk_destino=thunk_destino,
        tabla=tabla,
    )
    args.salida.parent.mkdir(parents=True, exist_ok=True)
    args.salida.write_text(txt, encoding="utf-8")
    print("[informe] %s (%d funciones) -> %s" % (args.evidencia, len(rows), args.salida))
    return 0


if __name__ == "__main__":
    sys.exit(main())
