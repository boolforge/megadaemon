#!/usr/bin/env python3
"""Convierte go.funcs.tsv (pclntab de Go) al formato de anchors de MegaDaemon.

El GhidraScript embebido en rust-core/src/ghidra.rs (MD_GHIDRA_SCRIPT, extraido
a tools/ghidra-scripts/MdGhidra.java) consume en modo "decompile" un TSV de
anchors con este formato:

    addr \t name \t orig \t loc \t tag

  addr : offset del ELF en hexadecimal (0x...)
  name : nombre simbolico (el que se aplica a la funcion)
  orig : nombre Go original (p.ej. google3/base/go/build.TimePST)
  loc  : fichero:linea original (p.ej. base/go/build.go:160)
  tag  : etiqueta (paquete) que decide el subdirectorio de salida

El script escribe un _decompile_report.tsv incremental (con flush), asi que el
barrido es reanudable: basta con quitar del anchors las filas ya reportadas.
"""

from __future__ import annotations

import argparse
import os
import re
import sys


def tag_de(fichero: str) -> str:
    """Etiqueta = los dos primeros segmentos de la ruta (el 'paquete')."""
    f = fichero.strip()
    if f.startswith("<"):
        return "autogenerated"
    partes = [p for p in f.split("/") if p]
    if not partes:
        return "raiz"
    if len(partes) == 1:
        return partes[0]
    return "/".join(partes[:2])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv", required=True, help="go.funcs.tsv")
    ap.add_argument("--salida", required=True)
    ap.add_argument("--solo-indice", default="", help="solo estos indices de shard (0/1/2), vacio = todos")
    ap.add_argument("--etiqueta", default="")
    args = ap.parse_args()

    filas = []
    with open(args.tsv, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            p = line.rstrip("\n").split("\t")
            if len(p) < 3:
                continue
            addr = p[0].strip()
            name = p[1].strip()
            resto = p[2]
            orig, _, loc = resto.partition(" | ")
            orig = orig.replace("go:", "", 1).strip()
            loc = loc.strip()
            filas.append((addr, name, orig, loc, tag_de(loc)))

    if args.etiqueta:
        filas = [f for f in filas if args.etiqueta in f[3] or args.etiqueta in f[1]]

    os.makedirs(os.path.dirname(os.path.abspath(args.salida)), exist_ok=True)
    with open(args.salida, "w", encoding="utf-8") as fh:
        for f in filas:
            fh.write("\t".join(f) + "\n")
    print(f"[anchors] {len(filas)} filas -> {args.salida}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
