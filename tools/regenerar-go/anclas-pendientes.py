#!/usr/bin/env python3
"""Anclas de las funciones de CODIGO REAL que aun no tienen pseudocodigo.

Cruza tres fuentes medidas:
  * NO-DECOMPIADAS.tsv  -> las funciones que el regenerador vio sin pseudocodigo
  * go.funcs.tsv        -> la direccion real (pclntab) y la ruta original
  * el informe del motor propio (out_md/motor_propio_4k/_decompile_report.tsv)
    -> lo que el motor sancionado ya decompilo por su cuenta

Se queda con las que NO son codigo generado (blaze-out/ y <autogenerated>),
que son las unicas que decompilar aporta: las generadas son tablas protobuf
y wrappers del compilador (sin logica).

Salida: TSV de anclas `addr \\t name \\t orig \\t loc \\t tag`, con la
direccion del PCLNTAB (el motor le suma el image base de Ghidra).
"""
from __future__ import annotations

import argparse
import os
import sys

CATEGORIAS = (
    "generado (blaze/protobuf)",
    "autogenerado (compilador)",
    "jetski (codigo propio de Antigravity)",
    "runtime Go",
    "librerias publicas (third_party/golang)",
    "otras third_party",
    "resto",
)
GENERADAS = {"generado (blaze/protobuf)", "autogenerado (compilador)"}


def categoria_de(fichero: str) -> str:
    f = fichero or ""
    if f.startswith("blaze-out/"):
        return CATEGORIAS[0]
    if f == "<autogenerated>":
        return CATEGORIAS[1]
    if f.startswith("third_party/jetski/"):
        return CATEGORIAS[2]
    if f.startswith("third_party/go/gc/"):
        return CATEGORIAS[3]
    if f.startswith("third_party/golang/"):
        return CATEGORIAS[4]
    if f.startswith("third_party/"):
        return CATEGORIAS[5]
    return CATEGORIAS[6]


def tag_de(fichero: str) -> str:
    """Etiqueta = los dos primeros segmentos de la ruta (el 'paquete')."""
    f = (fichero or "").strip()
    if f.startswith("<"):
        return "autogenerated"
    partes = [p for p in f.split("/") if p]
    if not partes:
        return "raiz"
    if len(partes) == 1:
        return partes[0]
    return "/".join(partes[:2])


def parse_loc(tercero: str) -> tuple[str, str]:
    if "|" not in tercero:
        return "", ""
    _, _, resto = tercero.partition("|")
    resto = resto.strip()
    if ":" not in resto:
        return resto, ""
    ruta, _, linea = resto.rpartition(":")
    return ruta.strip(), linea.strip()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv", default="/workspace/agy-re/tools-out/go.funcs.tsv")
    ap.add_argument("--nodec", default="/workspace/entrega/regenerado/NO-DECOMPIADAS.tsv")
    ap.add_argument(
        "--informes",
        default="/workspace/agy-re/tools-out/out_md/motor_propio_4k/_decompile_report.tsv",
        help="informes del motor propio: lo que ya decompilo (nombres, separados por coma)",
    )
    ap.add_argument("--salida", required=True)
    args = ap.parse_args()

    # 1) simbolos sin pseudocodigo (por simbolo+fichero+linea)
    sin = set()
    with open(args.nodec, encoding="utf-8", errors="replace") as fh:
        fh.readline()
        for line in fh:
            p = line.rstrip("\n").split("\t")
            if len(p) >= 3:
                sin.add((p[0], p[1], p[2]))
    print(f"[pendientes] NO-DECOMPIADAS: {len(sin)}")

    # 2) simbolos que el motor propio ya decompilo (por nombre)
    hechos = set()
    for inf in args.informes.split(","):
        inf = inf.strip()
        if not inf or not os.path.exists(inf):
            continue
        with open(inf, encoding="utf-8", errors="replace") as fh:
            fh.readline()
            for line in fh:
                p = line.rstrip("\n").split("\t")
                # SOLO cuentan las que el motor decompilo de verdad: las que
                # dejaron `dec_ok=false` (wrapper de Go que Ghidra no sabe
                # descompilar) siguen SIN pseudocodigo.
                if len(p) >= 2 and p[1] and (len(p) < 9 or p[8].lower() == "true"):
                    hechos.add(p[1])
        print(f"[pendientes] informe {os.path.basename(os.path.dirname(inf))}: {len(hechos)} simbolos")

    # 3) el pclntab
    filas = []
    n_gen = 0
    with open(args.tsv, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            p = line.rstrip("\n").split("\t")
            if len(p) < 3:
                continue
            addr, name, resto = p[0].strip(), p[1].strip(), p[2]
            orig, _, loc = resto.partition(" | ")
            orig = orig.replace("go:", "", 1).strip()
            ruta, linea = parse_loc(" | " + loc if "|" not in resto else resto)
            if not ruta:
                continue
            cat = categoria_de(ruta)
            if cat in GENERADAS:
                n_gen += 1
                continue
            clave = (name, ruta, linea)
            if clave not in sin:
                continue  # ya tiene pseudocodigo de otro shard
            if name in hechos:
                continue  # el motor propio ya lo decompilo
            filas.append((addr, name, orig, loc.strip(), tag_de(ruta), cat))

    os.makedirs(os.path.dirname(os.path.abspath(args.salida)), exist_ok=True)
    with open(args.salida, "w", encoding="utf-8") as fh:
        for f in filas:
            fh.write("\t".join(f[:5]) + "\n")
    print(f"[pendientes] generadas (excluidas): {n_gen}")
    print(f"[pendientes] de codigo real SIN pseudocodigo: {len(filas)} -> {args.salida}")
    from collections import Counter

    for c, n in Counter(f[5] for f in filas).most_common():
        print(f"    {n:>5}  {c}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
