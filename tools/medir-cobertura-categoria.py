#!/usr/bin/env python3
"""Cobertura por CATEGORIA de codigo de origen (MEDIDA).

go.funcs.tsv NO tiene cabecera. Sus columnas son:
    0: direccion (hex)
    1: simbolo del pclntab   (p.ej. archive_tar.__Format_.String)
    2: "go: <pkg>.<func> | <ruta>.go:<linea>"

NO-DECOMPIADAS.tsv SI tiene cabecera:
    simbolo \t fichero \t linea \t direccion \t error

El cruce es por (simbolo, fichero, linea) y la categoria sale de la ruta del
fichero original, con la misma regla que usa el generador (categoria_de).
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict

CATEGORIAS = (
    "generado (blaze/protobuf)",
    "autogenerado (compilador)",
    "jetski (codigo propio de Antigravity)",
    "runtime Go",
    "librerias publicas (third_party/golang)",
    "otras third_party",
    "resto",
)


def categoria_de(fichero: str) -> str:
    f = fichero or ""
    if f.startswith("blaze-out/"):
        return CATEGORIAS[0]
    if f == "<autogenerated>":
        return CATEGORIAS[1]
    if f.startswith("third_party/jetski/"):
        return CATEGORIAS[2]
    if f.startswith("third_party/go/gc/"):
        return CATEGORIAS[3]
    if f.startswith("third_party/golang/"):
        return CATEGORIAS[4]
    if f.startswith("third_party/"):
        return CATEGORIAS[5]
    return CATEGORIAS[6]


def parse_loc(tercero: str) -> tuple[str, str]:
    """'go: pkg.Func | ruta.go:47' -> ('ruta.go', '47')."""
    if "|" not in tercero:
        return "", ""
    _, _, resto = tercero.partition("|")
    resto = resto.strip()
    if ":" not in resto:
        return resto, ""
    ruta, _, linea = resto.rpartition(":")
    return ruta.strip(), linea.strip()


def main() -> int:
    tsv = sys.argv[1] if len(sys.argv) > 1 else "/workspace/agy-re/tools-out/go.funcs.tsv"
    nodec = sys.argv[2] if len(sys.argv) > 2 else "/workspace/entrega/regenerado/NO-DECOMPIADAS.tsv"
    out = sys.argv[3] if len(sys.argv) > 3 else "docs/medidas/cobertura_por_categoria.json"

    sin = set()
    with open(nodec, encoding="utf-8", errors="replace") as fh:
        fh.readline()
        for line in fh:
            p = line.rstrip("\n").split("\t")
            if len(p) >= 3:
                sin.add((p[0], p[1], p[2]))
    print(f"NO-DECOMPIADAS.tsv: {len(sin)} funciones sin pseudocodigo")

    total = Counter()
    cubier = Counter()
    ficheros = defaultdict(set)
    n = 0
    sin_clave = 0
    with open(tsv, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            p = line.rstrip("\n").split("\t")
            if len(p) < 3:
                continue
            n += 1
            simbolo = p[1]
            ruta, linea = parse_loc(p[2])
            c = categoria_de(ruta)
            total[c] += 1
            ficheros[c].add(ruta)
            if (simbolo, ruta, linea) not in sin:
                cubier[c] += 1
            else:
                sin_clave += 1
    print(f"TSV: {n} funciones · emparejadas con NO-DECOMPIADAS: {sin_clave}\n")

    filas = []
    print("| categoria | funciones | con pseudocodigo | % | ficheros |")
    print("|---|---:|---:|---:|---:|")
    for c in CATEGORIAS:
        t = total[c]
        if not t:
            continue
        k = cubier[c]
        pct = 100.0 * k / t
        filas.append(
            {
                "categoria": c,
                "funciones": t,
                "con_pseudocodigo": k,
                "pct": round(pct, 2),
                "ficheros": len(ficheros[c]),
            }
        )
        print(f"| {c} | {t} | {k} | {pct:.2f} % | {len(ficheros[c])} |")
    tt = sum(total.values())
    kk = sum(cubier.values())
    print(f"| **TOTAL** | **{tt}** | **{kk}** | **{100.0 * kk / tt:.2f} %** | |")
    filas.append(
        {
            "categoria": "TOTAL",
            "funciones": tt,
            "con_pseudocodigo": kk,
            "pct": round(100.0 * kk / tt, 2),
        }
    )
    with open(out, "w") as fh:
        json.dump(filas, fh, indent=2, ensure_ascii=False)
    print(f"\nescrito {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
